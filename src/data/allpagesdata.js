// Helper to retrieve or automatically generate rich metadata for every remaining menu URL
export function getPageData(slug) {
  const found = allPages.find(p => p.slug === slug);
  if (found) return found;

  const isPdf = slug.includes('pdf');
  const sizeMatch = slug.match(/(\d+)(kb|mb)/i);
  const targetVal = sizeMatch ? parseInt(sizeMatch[1]) : (isPdf ? 100 : 50);
  const targetUnit = sizeMatch ? sizeMatch[2].toUpperCase() : 'KB';
  const cleanTitle = slug.split('-').map(s => s.charAt(0).toUpperCase() + s.slice(1)).join(' ');

  let detectedCategory = 'image';
  if (isPdf) detectedCategory = 'pdf';
  if (slug.includes('convert') || slug.includes('to-')) detectedCategory = 'conversion';

  return {
    slug,
    category: detectedCategory,
    title: `${cleanTitle} - Free Online Tool | ConvertKB`,
    h1: cleanTitle,
    desc: `Easily process and optimize files with our ${cleanTitle.toLowerCase()} tool. Fast client-side quantization, aspect locking, and zero server uploads.`,
    targetKb: targetUnit === 'MB' ? targetVal * 1024 : targetVal,
    format: isPdf ? 'application/pdf' : 'image/jpeg',
    ratio: slug.includes('square') ? 1 : (slug.includes('passport') ? 3.5 / 4.5 : 0),
    portalSpec: {
      entity: "Digital Document Upload Standard",
      limit: `Target: ${targetVal} ${targetUnit}`,
      dim: "Auto-Preserved / Calibrated",
      ext: isPdf ? "PDF" : "JPEG / WebP / PNG"
    },
    focusKeyword: cleanTitle.toLowerCase()
  };
}
