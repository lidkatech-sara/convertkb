// src/data/contentEngine.js

export function generateFullContent(page = {}) {
  const h1 = page.h1 || "File Optimizer & Compressor";
  const category = page.category || (page.slug && page.slug.includes('pdf') ? 'pdf' : 'image');
  const targetKb = typeof page.targetKb === 'number' && !isNaN(page.targetKb) ? page.targetKb : 50;
  const focusKeyword = page.focusKeyword || h1.toLowerCase();

  const targetUnit = targetKb >= 1024 
    ? `${(targetKb / 1024).toFixed(targetKb % 1024 === 0 ? 0 : 1)}MB` 
    : `${targetKb}KB`;

  const rawSpec = page.portalSpec || {};
  const portalSpec = {
    entity: rawSpec.entity || "Standard Online Application Portals",
    limit: rawSpec.limit || `Strictly under ${targetUnit}`,
    dim: rawSpec.dim || "Auto-calibrated / Aspect Preserved",
    ext: rawSpec.ext || (category === 'pdf' ? "PDF" : "JPEG / WebP / PNG")
  };

  const isPdf = category === 'pdf';

  const specTable = [
    { label: "Target Application Category", value: portalSpec.entity },
    { label: "Permissible File Size Threshold", value: portalSpec.limit },
    { label: "Dimensional Constraints", value: portalSpec.dim },
    { label: "Output Format Standard", value: portalSpec.ext },
    { label: "Processing Mechanism", value: "Hardware-accelerated Client-Side V8 Sandbox" },
    { label: "Data Transmission Policy", value: "0% Server Upload - 100% Local Device Privacy" }
  ];

  const intro = `Compressing files to **${targetUnit}** while targeting **${focusKeyword}** requires precision balance between compression quantization and spatial fidelity. ConvertKB provides a browser-native studio environment to crop, rotate, correct exposure, calibrate DPI, and compress your file to exactly ${targetUnit} without exposing sensitive personal documents to remote cloud storage.`;

  const sections = [
    {
      h2: `1. Understanding the Engineering Behind ${h1}`,
      paragraphs: [
        `Modern smartphone cameras and digital scanners generate high-resolution image and document buffers containing millions of pixels. A standard 12MP or 48MP smartphone sensor generates uncompressed RAW image payloads ranging from 5MB to 25MB (5,000KB to 25,000KB). When online recruitment forms, consular visa databases, or academic management systems enforce hard thresholds around ${targetUnit}, standard linear compression tools simply downscale pixel resolution uniformly. This produces heavy pixelation, blurred cursive signatures, and obscured facial contours that trigger automated validation rejections.`,
        `ConvertKB solves this by applying discrete cosine transform (DCT) matrix quantization on images and stream-level object downsampling on PDF documents. Human visual perception prioritizes high-frequency luminance contours—such as the stroke of a black ink signature or the outline of facial features—over subtle background color gradations. By selectively stripping high-frequency chromatic noise while locking boundary contrast, ConvertKB allows files to hit a precise ${targetUnit} target with maximum visual sharpness.`,
        `All calculations execute client-side via hardware-accelerated Canvas and WebAssembly memory buffers. Your documents never touch external infrastructure or cloud databases, eliminating identity theft risks associated with traditional online file converters.`
      ]
    },
    {
      h2: isPdf ? "2. Multi-Page PDF Document Optimization Architecture" : "2. Aspect Ratio Preservation, Cropping, and DPI Calibration",
      paragraphs: isPdf ? [
        `Unlike text-only documents, multi-page PDFs generated by home flatbed scanners or smartphone scanning apps contain uncompressed 300 DPI raster scans on every page. A four-page academic transcript can easily exceed 8MB. Standard online PDF reducers only strip basic metadata tags (such as creator, author, and timestamp entries), saving an inconsequential 2KB to 5KB.`,
        `ConvertKB takes an architectural approach to PDF downsizing. Using Mozilla's PDF.js rendering runtime, the tool renders each PDF page into a virtual hardware-accelerated canvas at a calibrated resolution (150 DPI for documents, 72 DPI for web delivery). It flattens bloated layer trees, strips duplicate embedded font subsets, and quantizes raster streams. Finally, the pages are reassembled using PDF-Lib into an optimized container format that complies with official upload limits.`,
        `If your document contains color artifacts or shadow gradients from handheld phone captures, selecting ConvertKB's 'Grayscale' mode strips chrominance channels entirely. This reduces file size by up to 70% while improving text readability on screen.`
      ] : [
        `Aspect ratio distortion is one of the leading causes of application rejections on official job portals. For instance, if an online system expects a 3.5:4.5 cm passport ratio and you upload a square 1:1 image, automated screening bots will vertically compress or stretch your face to force it into their database constraints.`,
        `ConvertKB includes integrated Cropper.js controls with built-in aspect presets: 1:1 Square (UPSC & US Visa DS-160), 3.5:4.5 Passport (SSC, NEET, and International Passports), and 2:1 Rectangular (Candidate Signatures). Locking your crop box before compressing prevents accidental distortion.`,
        `Additionally, portals like NSDL PAN and state PSCs inspect EXIF headers for resolution density. ConvertKB allows you to specify 72, 150, 200, or 300 DPI directly in the output headers, satisfying automated metadata scanners.`
      ]
    },
    {
      h2: "3. Step-by-Step Walkthrough: Compressing and Editing Your File",
      paragraphs: [
        `Step 1: File Ingestion — Click the dropzone or drag your image (JPG, PNG, WebP, HEIC) or PDF directly into the studio card above. The file is read into your browser's local memory instantly without uploading to any server.`,
        `Step 2: Cropping and Orientation — For candidate photos or signatures, choose the appropriate aspect preset (e.g., 3.5:4.5 for passport portraits, 2:1 for signatures). Use the 90° rotation buttons if your phone captured the document in landscape orientation.`,
        `Step 3: Exposure and Contrast Tuning — If your signature or scanned document has a grayish background caused by poor lighting, select 'Document Whiten (B&W)' or increase the Contrast slider to 120%. This turns grayish paper into pure white (#FFFFFF), drastically reducing byte size.`,
        `Step 4: Target Threshold Verification — The target size is preset to ${targetUnit}. You can adjust this value if your specific notification mandates a different limit.`,
        `Step 5: Execution and Verification — Click 'Execute & Compress File'. ConvertKB executes an 8-iteration binary search algorithm to calibrate compression quality right under your specified target size. Review the before-and-after byte counter and click 'Download File' to save your file.`
      ]
    },
    {
      h2: "4. Official Submission Best Practices for Government Portals",
      paragraphs: [
        `Recruitment agencies like UPSC, SSC, IBPS, and consular visa portals process hundreds of thousands of candidate records daily. Follow these guidelines to ensure your submission passes automated checks:`,
        `• Signature Clarity: Always sign on smooth, unlined white paper using dark black or deep navy gel ink. Avoid ballpoint pens, as they produce faint, reflective lines that break down under compression.`,
        `• Even Portrait Lighting: Position your face toward an even, diffuse light source. Shadows across one side of the face or dark backgrounds can cause automated facial recognition bots to reject the upload.`,
        `• Avoid Double Compression: Compressing an already heavily compressed JPEG introduces generation loss (checkerboard block artifacts). Always start with your original high-resolution photo or scan, crop in ConvertKB, and compress down to ${targetUnit} in a single pass.`
      ]
    },
    {
      h2: "5. Privacy, Security, and Compliance Architecture",
      paragraphs: [
        `Identity cards, salary slips, marks sheets, and signatures contain sensitive personally identifiable information (PII). Transmitting these files to external third-party cloud conversion servers exposes users to data breaches, unauthorized caching, and surveillance.`,
        `ConvertKB operates under a zero-transmission model. All image processing, canvas operations, and PDF stream assemblies execute in client-side memory via WebAssembly and JavaScript engines. When you close the tab, all buffers are purged from your machine's temporary RAM. Your files never touch external storage.`
      ]
    }
  ];

  const faqs = [
    {
      q: `Will compressing my file to ${targetUnit} make text or details blurry?`,
      a: `No. ConvertKB prioritizes high-frequency contrast boundaries and removes low-frequency noise first, keeping text, signatures, and facial outlines sharp and legible.`
    },
    {
      q: `How does ConvertKB ensure my file lands under ${targetUnit}?`,
      a: `The engine runs a binary bisection search across canvas quality parameters, testing up to 8 compression iterations in browser memory to find the highest quality level that fits under ${targetUnit}.`
    },
    {
      q: `Can I calibrate the DPI to 200 DPI for exam portal compliance?`,
      a: `Yes. Use the Target DPI dropdown in the controls panel to set 72, 150, 200, or 300 DPI metadata directly into the file header.`
    },
    {
      q: `Are my confidential documents uploaded to any remote server?`,
      a: `No. ConvertKB processes all files locally inside your browser memory sandbox. No files are transmitted over the internet or saved to remote servers.`
    }
  ];

  return {
    intro,
    specTable,
    sections,
    faqs
  };
}
